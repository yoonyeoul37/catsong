/// 앱 언어 이름 → 번역표 칸 이름 (zh_Hant · zh · 나머지는 앞 두 글자)
String podLangOf(String localeName) {
  final l = localeName.replaceAll('-', '_');
  if (l.startsWith('zh')) {
    return (l.contains('Hant') || l.contains('TW') || l.contains('HK')) ? 'zh_Hant' : 'zh';
  }
  return l.split('_').first;
}

